#!/usr/bin/env python3
"""Generate THIRD-PARTY-LICENSES.md by harvesting license texts from the
vendored Cargo dependency sources. Walks the resolve graph from the `macros`
package following normal + build edges (excluding dev-dependencies), so it
covers exactly the crates that ship in the binary."""
import json
import os
import subprocess
import sys
from glob import glob

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

meta = json.loads(
    subprocess.check_output(
        ["cargo", "metadata", "--format-version", "1"], cwd=ROOT
    )
)
pkgs = {p["id"]: p for p in meta["packages"]}
root_id = next(p["id"] for p in meta["packages"] if p["name"] == "macros")

# Build the shipped set: BFS from root over non-dev dependency edges.
nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
shipped = set()
queue = [root_id]
while queue:
    nid = queue.pop()
    for dep in nodes[nid]["deps"]:
        kinds = dep.get("dep_kinds") or [{"kind": None}]
        if all(k.get("kind") == "dev" for k in kinds):
            continue
        if dep["pkg"] not in shipped and dep["pkg"] != root_id:
            shipped.add(dep["pkg"])
            queue.append(dep["pkg"])

LICENSE_GLOBS = ["LICENSE*", "LICENCE*", "COPYING*", "COPYRIGHT*", "NOTICE*", "UNLICENSE*"]


def license_files(crate_dir):
    found = []
    seen = set()
    for pat in LICENSE_GLOBS:
        for path in sorted(glob(os.path.join(crate_dir, pat))):
            name = os.path.basename(path)
            if name in seen or not os.path.isfile(path):
                continue
            # Skip obvious non-text (e.g. *.rs license modules).
            if name.lower().endswith((".rs", ".toml", ".md.html")):
                continue
            try:
                with open(path, "r", encoding="utf-8", errors="replace") as f:
                    text = f.read().strip()
            except OSError:
                continue
            if text:
                seen.add(name)
                found.append((name, text))
    return found


rows = []
for pid in shipped:
    p = pkgs[pid]
    crate_dir = os.path.dirname(p["manifest_path"])
    rows.append((p["name"], p["version"], p.get("license") or "UNSPECIFIED",
                 p.get("repository") or "", license_files(crate_dir)))
rows.sort(key=lambda r: (r[0].lower(), r[1]))

missing = [f"{n} {v}" for (n, v, lic, repo, files) in rows if not files]

out = [
    "# Third-party licenses",
    "",
    "Macros itself is licensed under the **MIT License** (see [`LICENSE`](LICENSE)).",
    "It links the Rust crates listed below; each is reproduced with its own",
    "license text as harvested from the crate source. This file is generated by",
    "`scripts/gen-third-party-licenses.py` — regenerate it after changing",
    "dependencies.",
    "",
    "See [`NOTICE`](NOTICE) for bundled non-code assets (the Lilex font and the",
    "GNU Emacs tutorial heritage) and for a note on the Magit / Treemacs /",
    "Org-mode / Helm reimplementations.",
    "",
    f"**{len(rows)} crates** ship in the binary.",
    "",
    "---",
    "",
]
for name, version, lic, repo, files in rows:
    out.append(f"## {name} {version}")
    out.append("")
    out.append(f"- License (SPDX): `{lic}`")
    if repo:
        out.append(f"- Repository: {repo}")
    out.append("")
    if files:
        for fname, text in files:
            out.append(f"<details><summary>{fname}</summary>")
            out.append("")
            out.append("```")
            out.append(text)
            out.append("```")
            out.append("")
            out.append("</details>")
            out.append("")
    else:
        out.append(
            f"_No license file is bundled in this crate's source; it declares "
            f"`{lic}` in its manifest — see the Common licenses appendix below._"
        )
        out.append("")
    out.append("---")
    out.append("")

# Appendix: canonical full texts for crates that declare a license but ship no
# license file (see scripts/license-texts/). Covers the families those crates use.
texts_dir = os.path.join(ROOT, "scripts", "license-texts")
appendix = sorted(glob(os.path.join(texts_dir, "*.txt")))
if appendix:
    out.append("# Common licenses")
    out.append("")
    out.append(
        "Full text of the licenses declared by crates that ship no license file "
        "in their source. Canonical texts from the SPDX license list."
    )
    out.append("")
    for path in appendix:
        spdx = os.path.splitext(os.path.basename(path))[0]
        with open(path, "r", encoding="utf-8", errors="replace") as f:
            text = f.read().strip()
        out.append(f"## {spdx}")
        out.append("")
        out.append("```")
        out.append(text)
        out.append("```")
        out.append("")
        out.append("---")
        out.append("")

dest = os.path.join(ROOT, "THIRD-PARTY-LICENSES.md")
with open(dest, "w", encoding="utf-8") as f:
    f.write("\n".join(out))

print(f"Wrote {dest}: {len(rows)} crates, {len(missing)} without a bundled license file.")
if missing:
    print("Crates with no bundled license file (SPDX recorded):", file=sys.stderr)
    for m in missing:
        print("  " + m, file=sys.stderr)
