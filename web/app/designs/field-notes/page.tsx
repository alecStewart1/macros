const heatGrid: number[][] = (() => {
  const r = rng(42);
  const hourShape = (h: number) =>
    Math.exp(-((h - 10.5) ** 2) / 5) * 1.0 +
    Math.exp(-((h - 15.5) ** 2) / 6) * 0.9 +
    Math.exp(-((h - 22) ** 2) / 2.5) * 0.35;
  return Array.from({ length: HOURS }, (_, h) =>
    Array.from({ length: DAYS }, (_, d) => {
      const weekend = d % 7 >= 5;
      const shape = weekend ? Math.exp(-((h - 21) ** 2) / 4) * 0.45 : hourShape(h);
      return Math.max(0, shape * 1000 + gaussian(r) * 60);
    }),
  );
})();
