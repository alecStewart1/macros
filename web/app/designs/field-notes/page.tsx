// Table 1 — illustrative small multiples (a synthetic 30-day session).
function series(seed: number, base: number, amp: number, trend: number, weekly = true) {
  const r = rng(seed);
  return Array.from({ length: 30 }, (_, d) => {
    const weekend = weekly && d % 7 >= 5 ? 0.35 : 1;
    const v = (base + trend * d + amp * Math.sin(d / 3 + seed)) * weekend + gaussian(r) * amp * 0.35;
    return Math.max(0, Math.round(v));
  });
}
